use freergb_core::Rgb;
pub fn direct(c0: Rgb, c1: Rgb) -> [u8; 60] {
    let mut b = [0u8; 60];
    b[0x00] = 0x20; // 32
    b[0x01] = 0x03;
    b[0x02] = 0x01;
    b[0x03] = 0x00; // static single mode
    b[0x04] = 0x02; // speed medium
    b[0x05] = 0x03; // brightness high
    b[0x06] = 0x00; // clockwise
    b[0x07] = 0x01;
    b[0x08] = 0x02;
    b[0x09] = 0xFF;
    b[0x0D] = 0x01;
    b[0x0E] = 0x03;
    b[0x0F] = 0xFF;
    b[0x10] = 0x7F;
    b[0x13] = 0x01;
    b[0x14] = 0x04;
    b[0x17] = 0xFF;
    b[0x19] = 0x01;
    b[0x1A] = 0x05;
    b[0x1C] = 0xFF;
    b[0x1F] = 0x01;
    b[0x20] = 0x06;
    b[0x21] = 0xFF;
    b[0x23] = 0xFF;
    b[0x25] = 0x01;
    b[0x26] = 0x07;
    b[0x27] = 0xFF;
    b[0x28] = 0xFF;
    b[0x2C] = 0x0A;
    b[0x2D] = 0x0A;
    b[0x30] = 0x14;
    b[0x31] = 0x08;
    b[0x3A] = 0x32;
    b[0x3B] = 0x32;
    b[0x33] = c0.r;
    b[0x34] = c0.g;
    b[0x35] = c0.b;
    b[0x36] = c1.r;
    b[0x37] = c1.g;
    b[0x38] = c1.b;
    b
}
