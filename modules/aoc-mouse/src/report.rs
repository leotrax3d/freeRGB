use freergb_core::Rgb;
pub fn direct(c0: Rgb, c1: Rgb) -> [u8; 60] {
    let mut b = [0u8; 60];
    for (idx, val) in [
        (0usize, 0x20u8),
        (1, 0x03),
        (2, 0x01),
        (3, 0x00),
        (4, 0x02),
        (5, 0x03),
        (6, 0x00),
        (7, 0x01),
        (8, 0x02),
        (9, 0xFF),
        (0x0D, 0x01),
        (0x0E, 0x03),
        (0x0F, 0xFF),
        (0x10, 0x7F),
        (0x13, 0x01),
        (0x14, 0x04),
        (0x17, 0xFF),
        (0x19, 0x01),
        (0x1A, 0x05),
        (0x1C, 0xFF),
        (0x1F, 0x01),
        (0x20, 0x06),
        (0x21, 0xFF),
        (0x23, 0xFF),
        (0x25, 0x01),
        (0x26, 0x07),
        (0x27, 0xFF),
        (0x28, 0xFF),
        (0x2C, 0x0A),
        (0x2D, 0x0A),
        (0x30, 0x14),
        (0x31, 0x08),
        (0x3A, 0x32),
        (0x3B, 0x32),
    ] {
        b[idx] = val;
    }
    b[0x33] = c0.r;
    b[0x34] = c0.g;
    b[0x35] = c0.b;
    b[0x36] = c1.r;
    b[0x37] = c1.g;
    b[0x38] = c1.b;
    b
}
