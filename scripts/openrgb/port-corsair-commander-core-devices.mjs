// Generator for the Corsair Commander Core module device table.
// Usage: node scripts/openrgb/port-corsair-commander-core-devices.mjs <openrgb-root> <commit>
// Reads CorsairCommanderCoreControllerDetect.cpp and CorsairCommanderCoreController.h
// and regenerates modules/corsair-commander-core/src/devices_table.rs.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = process.argv[2] ?? process.env.OPENRGB_ROOT ?? '../openrgb';
const commit = process.argv[3] ?? 'unknown';
const family = path.join(root, 'Controllers', 'CorsairCommanderCoreController');
const detect = fs.readFileSync(path.join(family, 'CorsairCommanderCoreControllerDetect.cpp'), 'utf8');
const header = fs.readFileSync(path.join(family, 'CorsairCommanderCoreController.h'), 'utf8');

const constants = Object.fromEntries(
  [detect, header]
    .flatMap((t) => [...t.matchAll(/#define\s+(CORSAIR[A-Z0-9_]*)\s+0x([0-9A-Fa-f]+)/g)])
    .map((m) => [m[1], Number.parseInt(m[2], 16)]),
);
if (constants.CORSAIR_VID == null) throw new Error('CORSAIR_VID not found');

const rows = [];
for (const m of detect.matchAll(
  /REGISTER_HID_DETECTOR[A-Z_]*\s*\(\s*"([^"]+)"\s*,\s*([A-Za-z0-9_]+)\s*,\s*CORSAIR_VID\s*,\s*(CORSAIR[A-Z0-9_]+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*,\s*(0x[0-9A-Fa-f]+)\s*,\s*(0x[0-9A-Fa-f]+|\d+)\s*\)/g,
)) {
  const pid = constants[m[3]];
  if (pid == null) throw new Error(`unresolved PID ${m[3]} in detector row ${m[1]}`);
  rows.push({
    name: m[1],
    handler: m[2],
    vid: constants.CORSAIR_VID,
    pid,
    interface: m[4].startsWith('0x')
      ? Number.parseInt(m[4].slice(2), 16)
      : Number.parseInt(m[4], 10),
    usagePage: Number.parseInt(m[5], 16),
    usagePage: Number.parseInt(m[5], 16),
    usage: Number.parseInt(m[6].startsWith('0x') ? m[6].slice(2) : m[6], 16),
  });
}
if (rows.length === 0) throw new Error('no Corsair Commander Core detectors parsed');

const out = path.join(process.cwd(), 'modules', 'corsair-commander-core', 'src', 'devices_table.rs');
const lines = [
  '// SPDX-License-Identifier: GPL-2.0-or-later',
  `// Generated by scripts/openrgb/port-corsair-commander-core-devices.mjs from OpenRGB ${commit}; do not edit.`,
  'use crate::table::Detector;',
  '',
  'pub const DETECTORS: &[Detector] = &[',
  ...rows.map(
    (d) =>
      `    Detector { name: ${JSON.stringify(d.name)}, handler: ${JSON.stringify(d.handler)}, vid: 0x${d.vid.toString(16).padStart(4, '0')}, pid: 0x${d.pid.toString(16).padStart(4, '0')}, interface: ${d.interface}, usage_page: 0x${d.usagePage.toString(16)}, usage: 0x${d.usage.toString(16)} },`,
  ),
  '];',
  '',
];
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
execFileSync(process.platform === 'win32' ? 'rustfmt.exe' : 'rustfmt', [out], { stdio: 'ignore' });
console.log(`generated ${rows.length} Corsair Commander Core HID detectors`);