// Generator for the Anne Pro 2 module device table and LED name table.
// Usage: node scripts/openrgb/port-annepro2-devices.mjs <openrgb-root> <commit>
// Reads AnnePro2ControllerDetect.cpp and RGBController_AnnePro2.cpp and regenerates
// modules/annepro2/src/devices_table.rs and modules/annepro2/src/led_names.rs.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = process.argv[2] ?? process.env.OPENRGB_ROOT ?? '../openrgb';
const commit = process.argv[3] ?? 'unknown';
const family = path.join(root, 'Controllers', 'AnnePro2Controller');
const detect = fs.readFileSync(path.join(family, 'AnnePro2ControllerDetect.cpp'), 'utf8');
const rgb = fs.readFileSync(path.join(family, 'RGBController_AnnePro2.cpp'), 'utf8');

const constants = Object.fromEntries(
  [...detect.matchAll(/#define\s+([A-Z][A-Z0-9_]*)\s+0x([0-9A-Fa-f]+)/g)].map((m) => [
    m[1],
    Number.parseInt(m[2], 16),
  ]),
);
if (constants.ANNE_PRO_2_VID_1 == null) throw new Error('ANNE_PRO_2_VID_1 not found');
const n = (s) => constants[s.trim()] ?? Number.parseInt(s.trim(), 16);

const rows = [];
for (const m of detect.matchAll(
  /REGISTER_HID_DETECTOR(?:_I)?\s*\(\s*"([^"]+)"\s*,\s*([A-Za-z0-9_]+)\s*,\s*(ANNE_PRO_2_VID_[0-9])\s*,\s*(ANNE_PRO_2_PID_[0-9])\s*,\s*(\d+)\s*\)/g,
)) {
  const vid = n(m[3]);
  const pid = n(m[4]);
  if (!Number.isFinite(vid) || !Number.isFinite(pid)) {
    throw new Error(`unresolved VID/PID ${m[3]}/${m[4]} in detector row ${m[1]}`);
  }
  rows.push({ name: m[1], handler: m[2], vid, pid, interface: Number.parseInt(m[5], 10) });
}
if (rows.length === 0) throw new Error('no Anne Pro 2 detectors parsed');

// LED names with real frame indices from RGBController_AnnePro2.cpp led_names[].
const names = [];
for (const m of rgb.matchAll(/\{\s*(KEY_[A-Z0-9_]+),\s*(\d+)\s*\}/g)) {
  names.push({ name: m[1], index: Number.parseInt(m[2], 10) });
}
if (names.length !== 61) throw new Error(`expected 61 led_names entries, got ${names.length}`);

const out = path.join(process.cwd(), 'modules', 'annepro2', 'src', 'devices_table.rs');
const lines = [
  '// SPDX-License-Identifier: GPL-2.0-or-later',
  `// Generated by scripts/openrgb/port-annepro2-devices.mjs from OpenRGB ${commit}; do not edit.`,
  'use crate::table::Detector;',
  '',
  'pub const DETECTORS: &[Detector] = &[',
  ...rows.map(
    (d) =>
      `    Detector { name: ${JSON.stringify(d.name)}, handler: ${JSON.stringify(d.handler)}, vid: 0x${d.vid.toString(16).padStart(4, '0')}, pid: 0x${d.pid.toString(16).padStart(4, '0')}, interface: ${d.interface} },`,
  ),
  '];',
  '',
];
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));

const namesOut = path.join(process.cwd(), 'modules', 'annepro2', 'src', 'led_names.rs');
const nameLines = [
  '// SPDX-License-Identifier: GPL-2.0-or-later',
  `// Generated by scripts/openrgb/port-annepro2-devices.mjs from OpenRGB ${commit}; do not edit.`,
  '// LED index in the real (gap-bearing) frame per upstream RGBController_AnnePro2.cpp led_names[].',
  'pub static LED_NAMES: &[(&str, usize)] = &[',
  ...names.map((d) => `    (${JSON.stringify(d.name)}, ${d.index}),`),
  '];',
  '',
];
fs.writeFileSync(namesOut, nameLines.join('\n'));
execFileSync(process.platform === 'win32' ? 'rustfmt.exe' : 'rustfmt', [out, namesOut], {
  stdio: 'ignore',
});
console.log(`generated ${rows.length} Anne Pro 2 HID detectors and ${names.length} LED names`);