// Build a complete, deterministic OpenRGB controller-family inventory.
// Usage: node scripts/openrgb/inventory.mjs <openrgb-checkout> <40-hex-commit>
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join, relative, basename } from "node:path";

const [checkout, commit] = process.argv.slice(2);
if (!checkout || !/^[0-9a-f]{40}$/.test(commit ?? "")) {
  console.error("usage: inventory.mjs <openrgb-checkout> <40-hex-commit>");
  process.exit(2);
}
const existingDoc = (() => { try { return readFileSync(join(process.cwd(), "docs/OPENRGB_PORTING.md"), "utf8"); } catch { return ""; } })();
const preservedStatus = existingDoc.includes("## Port status ledger")
  ? existingDoc.slice(existingDoc.indexOf("## Port status ledger"))
  : "## Port status ledger\n\nNo families ported in this inventory run yet.\n";

const controllers = join(checkout, "Controllers");
const walk = (dir) => readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
  const path = join(dir, entry.name);
  return entry.isDirectory() ? walk(path) : [path];
});
const sourceFiles = (dir) => walk(dir).filter((p) => /\.(cpp|h|hpp|c|cc)$/i.test(p));
const splitArgs = (text) => text.split(/,(?![^()]*\))/).map((s) => s.trim());
const detectorPattern = /REGISTER_HID_DETECTOR(?:_[A-Z]+)?\s*\(([^;]*?)\)\s*;/g;
const spdxPattern = /SPDX-License-Identifier:\s*([^\r\n*\\]+)/g;
const includePattern = /^\s*#include\s*[<"]([^>"]+)[>"]/gm;

const classify = (text) => {
  const nonHid = [];
  if (/\b(SMBus|I2C|PCI|NvAPI|SuperIO|TCP|UDP|socket|Yeelight|PhilipsHue|LinuxLED)\b/i.test(text)) nonHid.push("non-HID references");
  const hid = /hidapi|hid_device|REGISTER_HID_DETECTOR|hid_write|hid_send_feature_report/i.test(text);
  return nonHid.length ? (hid ? "HID + other" : "other") : (hid ? "USB HID" : "unknown");
};

const rows = [];
for (const dirent of readdirSync(controllers, { withFileTypes: true }).filter((e) => e.isDirectory())) {
  const dir = join(controllers, dirent.name);
  const files = sourceFiles(dir);
  const contents = files.map((path) => readFileSync(path, "utf8"));
  const text = contents.join("\n");
  const detectors = [...text.matchAll(detectorPattern)].map((m) => splitArgs(m[1]));
  if (!detectors.length) continue;
  const devices = new Set(detectors.map((args) => args.slice(2, 4).join(" / ")));
  const licenses = new Set();
  for (const content of contents) for (const m of content.slice(0, 4000).matchAll(spdxPattern)) licenses.add(m[1].replace(/[|\r\n]/g, "").trim());
  const includes = new Set();
  for (const content of contents) for (const m of content.matchAll(includePattern)) {
    const include = m[1];
    if (!include.includes("/") || include.endsWith(".h")) includes.add(basename(include));
  }
  const shared = [...includes].filter((name) => /KeyboardLayout|Layout|DetectionManager|RGBController|hidapi|StringUtils|Configuration/i.test(name));
  rows.push({
    family: dirent.name,
    detectors: detectors.length,
    devices: devices.size,
    files: files.length,
    lines: contents.reduce((sum, content) => sum + content.split(/\r?\n/).length, 0),
    transport: classify(text),
    licenses: [...licenses].sort().join(", ") || "missing SPDX header",
    dependencies: shared.sort().join(", ") || "—",
  });
}
rows.sort((a, b) => b.devices - a.devices || b.detectors - a.detectors || a.family.localeCompare(b.family));
const hid = rows.filter((row) => row.transport === "USB HID" || row.transport === "HID + other");
const totalDetectors = rows.reduce((n, row) => n + row.detectors, 0);
const totalDevices = rows.reduce((n, row) => n + row.devices, 0);
const table = rows.map((row, index) => `| ${index + 1} | \`${row.family}\` | ${row.devices} | ${row.detectors} | ${row.files} | ${row.lines.toLocaleString("en-US")} | ${row.transport} | ${row.dependencies} | ${row.licenses} |`).join("\n");
const excluded = rows.filter((row) => row.transport !== "USB HID" && row.transport !== "HID + other").map((row) => `- \`${row.family}\`: ${row.transport}`).join("\n");
const markdown = `# OpenRGB controller-family porting inventory

Generated by \`scripts/openrgb/inventory.mjs\` from OpenRGB commit \`${commit}\`. The source scan includes every directory under \`Controllers/\` containing at least one \`REGISTER_HID_DETECTOR*\` registration. Device entries are unique detector VID/PID expressions; detector registrations are counted separately.

Summary: **${rows.length} families**, **${totalDetectors} detector registrations**, **${totalDevices} unique detector VID/PID entries**. USB-HID queue: **${hid.length} families**. The table is the authoritative priority order: device entries descending, then detectors descending, then name.

| Priority | Family | Devices | Detectors | Files | Lines | Transport | Shared dependencies | SPDX headers |
|---:|---|---:|---:|---:|---:|---|---|---|
${table}

## Policy corrections

* \`MSIMotherboardController\` and \`AsusAuraUSBController\` are USB-HID families and are listed as such. The ASUS 0b05:19af device is excluded from future freeRGB claims because the built-in adapter owns it.
* \`CorsairPeripheralController\` and \`CorsairPeripheralV2Controller\` remain HID candidates; only K70 CORE (1b1c:1bfd/1bff) and iCUE LINK (1b1c:0c3f) are excluded from module claims.
* SMBus/I2C/PCI/serial/network paths remain visible in this inventory but are not eligible for a USB-HID module until a separately authorized transport exists.

## Non-HID or mixed families

${excluded}

${preservedStatus}

The per-family status ledger is maintained below this inventory by the porting
workflow. A family may be marked blocked only for an actual non-HID transport,
unclear upstream licensing or missing upstream hardware information. User-sized
LED layouts use the optional initialize \`zones\` parameter documented in
\`docs/HARDWARE_MODULES.md\`.
`;
writeFileSync(join(process.cwd(), "docs/OPENRGB_PORTING.md"), markdown);
console.log(`${rows.length} families, ${totalDetectors} detectors, ${totalDevices} unique VID/PID entries, ${hid.length} HID/mixed`);
