// Generator for the Corsair Hydro Platinum module device table.
// Usage: node scripts/openrgb/port-corsair-hydro-platinum-devices.mjs <openrgb-root> <commit>
// Reads Controllers/CorsairHydroPlatinumController/CorsairHydroPlatinumControllerDetect.cpp
// and regenerates modules/corsair-hydro-platinum/src/devices_table.rs.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = process.argv[2] ?? process.env.OPENRGB_ROOT ?? '../openrgb';
const commit = process.argv[3] ?? 'unknown';
const family = path.join(root, 'Controllers', 'CorsairHydroPlatinumController');
const detect = fs.readFileSync(
  path.join(family, 'CorsairHydroPlatinumControllerDetect.cpp'),
  'utf8',
);

const constants = Object.fromEntries(
  [...detect.matchAll(/#define\s+(CORSAIR[A-Z0-9_]*)\s+0x([0-9A-Fa-f]+)/g)].map((m) => [
    m[1],
    Number.parseInt(m[2], 16),
  ]),
);
if (constants.CORSAIR_VID == null) throw new Error('CORSAIR_VID not found');

// PIDs without an RGB fan (upstream no_rgb_fan_models[] in the detector).
const noFanBlock = detect.slice(
  detect.indexOf('no_rgb_fan_models'),
  detect.indexOf('};', detect.indexOf('no_rgb_fan_models')),
);
const noRgbFan = [...noFanBlock.matchAll(/CORSAIR[A-Z0-9_]+/g)].map((m) => {
  const pid = constants[m[0]];
  if (pid == null) throw new Error(`unresolved PID ${m[0]}`);
  return pid;
});

const rows = [];
for (const m of detect.matchAll(
  /REGISTER_HID_DETECTOR\s*\(\s*"([^"]+)"\s*,\s*([A-Za-z0-9_]+)\s*,\s*CORSAIR_VID\s*,\s*(CORSAIR[A-Z0-9_]+)\s*\)/g,
)) {
  const pid = constants[m[3]];
  if (pid == null) throw new Error(`unresolved PID ${m[3]} in detector row ${m[1]}`);
  rows.push({
    name: m[1],
    handler: m[2],
    vid: constants.CORSAIR_VID,
    pid,
    rgbFan: !noRgbFan.includes(pid),
  });
}
if (rows.length === 0) throw new Error('no Corsair Hydro Platinum detectors parsed');

const out = path.join(process.cwd(), 'modules', 'corsair-hydro-platinum', 'src', 'devices_table.rs');
const lines = [
  '// SPDX-License-Identifier: GPL-2.0-or-later',
  `// Generated by scripts/openrgb/port-corsair-hydro-platinum-devices.mjs from OpenRGB ${commit}; do not edit.`,
  'use crate::table::{Detector, Device};',
  '',
  'pub const DETECTORS: &[Detector] = &[',
  ...rows.map(
    (d) =>
      `    Detector { name: ${JSON.stringify(d.name)}, handler: ${JSON.stringify(d.handler)}, vid: 0x${d.vid.toString(16).padStart(4, '0')}, pid: 0x${d.pid.toString(16).padStart(4, '0')} },`,
  ),
  '];',
  '',
  'pub const DEVICES: &[Device] = &[',
  ...rows.map(
    (d) =>
      `    Device { vid: 0x${d.vid.toString(16).padStart(4, '0')}, pid: 0x${d.pid.toString(16).padStart(4, '0')}, rgb_fan: ${d.rgbFan} },`,
  ),
  '];',
  '',
];
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
execFileSync(process.platform === 'win32' ? 'rustfmt.exe' : 'rustfmt', [out], { stdio: 'ignore' });
console.log(`generated ${rows.length} Corsair Hydro Platinum HID detectors`);