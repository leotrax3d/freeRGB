import fs from 'node:fs';
const commit = process.argv[3] ?? 'unknown';
// upstream: AsusAuraUSBControllerDetect.cpp registers the mice via
// REGISTER_HID_DETECTOR_IP rows (interface 0, usage page 0xFF01, usage
// unconstrained). Only the PIDs whose aura_mouse_devices entry sets
// direct=true are claimed: the others have no native Direct mode (they use
// Static-as-direct, which is an effect mode upstream, not per-LED direct).
// The Spatha X Dock row shares PID 0x1979 with the 2.4GHz mouse and is told
// apart by the product string "Asus ROG Spatha X Dock"; the dock has
// direct=false and stays unsupported.
const row = (name, vid, pid, product) => `    Detector { name: ${JSON.stringify(name)}, vid: ${vid}, pid: ${pid}, interface: 0, usage_page: 0xff01, product: ${product} },`;
const out = [
    '// SPDX-License-Identifier: GPL-2.0-or-later',
    `// Generated by scripts/openrgb/port-asus-aura-mouse-devices.mjs from OpenRGB ${commit}; do not edit.`,
    'use crate::table::Detector;',
    '',
    'pub const DETECTORS: &[Detector] = &[',
    row('ASUS ROG Gladius III Wireless AimPoint USB', '0x0b05', '0x1a70', 'None'),
    row('ASUS ROG Gladius III Wireless AimPoint 2.4Ghz', '0x0b05', '0x1a72', 'None'),
    row('ASUS ROG Keris Wireless AimPoint USB', '0x0b05', '0x1a66', 'None'),
    row('ASUS ROG Keris Wireless AimPoint 2.4Ghz', '0x0b05', '0x1a68', 'None'),
    row('Asus ROG Chakram X USB', '0x0b05', '0x1a18', 'None'),
    row('Asus ROG Chakram X 2.4GHz', '0x0b05', '0x1a1a', 'None'),
    row('Asus ROG Spatha X USB', '0x0b05', '0x1977', 'None'),
    row('Asus ROG Spatha X 2.4GHz', '0x0b05', '0x1979', 'Some("Asus ROG Spatha X 2.4GHz")'),
    row('ASUS ROG Strix Impact III', '0x0b05', '0x1a88', 'None'),
    '];',
];
fs.writeFileSync('modules/asus-aura-mouse/src/devices_table.rs', out.join('\n'));
console.log('generated 9 ASUS Aura mouse rows');
