// Generator for the Corsair peripheral module device table.
// Usage: node scripts/openrgb/port-corsair-peripheral-devices.mjs <openrgb-root> <commit>
// Reads Controllers/CorsairPeripheralController/CorsairPeripheralControllerDetect.cpp
// and regenerates modules/corsair-peripheral/src/devices_table.rs.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = process.argv[2] ?? process.env.OPENRGB_ROOT ?? '../openrgb';
const commit = process.argv[3] ?? 'unknown';
const detect = fs.readFileSync(
  path.join(root, 'Controllers', 'CorsairPeripheralController', 'CorsairPeripheralControllerDetect.cpp'),
  'utf8',
);

const constants = Object.fromEntries(
  [...detect.matchAll(/#define\s+(CORSAIR[A-Z0-9_]*)\s+0x([0-9A-Fa-f]+)/g)].map((m) => [
    m[1],
    Number.parseInt(m[2], 16),
  ]),
);
if (constants.CORSAIR_VID == null) throw new Error('CORSAIR_VID not found');

const rows = [];
for (const m of detect.matchAll(
  /REGISTER_HID_DETECTOR[A-Z_]*\s*\(\s*"([^"]+)"\s*,\s*([A-Za-z0-9_]+)\s*,\s*CORSAIR_VID\s*,\s*(CORSAIR[A-Z0-9_]+)\s*(?:,[^)]*)?\)/g,
)) {
  const pid = constants[m[3]];
  if (pid == null) throw new Error(`unresolved PID ${m[3]} in detector row ${m[1]}`);
  rows.push({ name: m[1], handler: m[2], vid: constants.CORSAIR_VID, pid });
}
if (rows.length === 0) throw new Error('no Corsair peripheral detectors parsed');

const out = path.join(process.cwd(), 'modules', 'corsair-peripheral', 'src', 'devices_table.rs');
const lines = [
  '// SPDX-License-Identifier: GPL-2.0-or-later',
  `// Generated by scripts/openrgb/port-corsair-peripheral-devices.mjs from OpenRGB ${commit}; do not edit.`,
  'use crate::table::Detector;',
  '',
  'pub const DETECTORS: &[Detector] = &[',
  ...rows.map(
    (d) =>
      `    Detector { name: ${JSON.stringify(d.name)}, handler: ${JSON.stringify(d.handler)}, vid: 0x${d.vid.toString(16).padStart(4, '0')}, pid: 0x${d.pid.toString(16).padStart(4, '0')} },`,
  ),
  '];',
  '',
];
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
execFileSync(process.platform === 'win32' ? 'rustfmt.exe' : 'rustfmt', [out], { stdio: 'ignore' });
console.log(`generated ${rows.length} Corsair peripheral HID detectors`);