import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';
const root = process.argv[2] ?? process.env.OPENRGB_ROOT ?? (() => { throw new Error('Pass the OpenRGB checkout as argv[2] or set OPENRGB_ROOT'); })();
const family = path.join(root, 'Controllers', 'SteelSeriesController');
const source = path.join(family, 'SteelSeriesControllerDetect.cpp');
const text = fs.readFileSync(source, 'utf8');
const all = fs.readdirSync(family, { recursive: true }).filter(f => /\.(cpp|h)$/.test(f)).map(f => fs.readFileSync(path.join(family, f), 'utf8')).join('\n');
const constants = Object.fromEntries([...all.matchAll(/#define\s+([A-Z][A-Z0-9_]+)\s+0x([0-9A-Fa-f]+)/g)].map(m => [m[1], Number.parseInt(m[2], 16)]));
constants.STEELSERIES_VID ??= 0x1038;
const n = s => constants[s.trim()] ?? Number.parseInt(s.trim(), 16);
const rows = [];
for (const m of text.matchAll(/REGISTER_HID_DETECTOR[A-Z_]*\s*\(\s*"([^"]+)"\s*,\s*([A-Za-z0-9_]+)[\s\S]*?STEELSERIES_VID\s*,\s*([^,\s)]+)([^)]*)\)/g)) {
  const pid = n(m[3]); if (!Number.isFinite(pid)) continue;
  rows.push({ name: m[1], handler: m[2], vid: 0x1038, pid });
}
const out = path.join(process.cwd(), 'modules', 'steelseries', 'src', 'devices_table.rs');
const lines = ['// SPDX-License-Identifier: GPL-2.0-or-later', '// Generated by scripts/openrgb/port-steelseries-devices.mjs; do not edit.', 'use crate::table::Detector;', '', 'pub const DETECTORS: &[Detector] = &[', ...rows.map(d => `    Detector { name: ${JSON.stringify(d.name)}, handler: ${JSON.stringify(d.handler)}, vid: 0x${d.vid.toString(16).padStart(4,'0')}, pid: 0x${d.pid.toString(16).padStart(4,'0')} },`), '];', ''];
fs.mkdirSync(path.dirname(out), { recursive: true }); fs.writeFileSync(out, lines.join('\n')); execFileSync(process.platform === 'win32' ? 'rustfmt.exe' : 'rustfmt', [out], { stdio: 'ignore' });
console.log(`generated ${rows.length} SteelSeries HID detectors`);
