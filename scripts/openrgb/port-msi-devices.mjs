// Generate the MSI Mystic Light detector table from the pinned OpenRGB tree.
import fs from 'node:fs';
import path from 'node:path';
import { execFileSync } from 'node:child_process';

const root = process.argv[2] ?? process.env.OPENRGB_ROOT ?? 'C:/Users/harald/AppData/Local/Temp/freergb-openrgb-bbc77470';
const source = path.join(root, 'Controllers', 'MSIMotherboardController', 'MSIMotherboardControllerDetect.cpp');
const text = fs.readFileSync(source, 'utf8');
const vid = { MSI_USB_VID: 0x1462, MSI_USB_VID_COMMON: 0x0db0 };
const pid = { MSI_USB_PID_COMMON: 0x0076 };
const number = (s, constants) => constants[s.trim()] ?? Number.parseInt(s.trim(), 16);
const detectors = [...text.matchAll(/REGISTER_HID_DETECTOR_PU\(\s*"([^"]+)"\s*,[^,]+,\s*([^,]+),\s*([^,]+)\s*,\s*(0x[0-9a-fA-F]+)\s*,\s*(0x[0-9a-fA-F]+)/g)]
  .map((m) => ({ name: m[1], vid: vid[m[2].trim()], pid: number(m[3], pid), interface: Number.parseInt(m[4], 16), usage: Number.parseInt(m[5], 16), variant: Number.parseInt(m[6], 16) }))
  .filter((d) => d.vid !== undefined);
if (detectors.length === 0) throw new Error(`no MSI detectors found in ${source}`);
const lines = [
  '// SPDX-License-Identifier: GPL-2.0-or-later',
  '// Generated by scripts/openrgb/port-msi-devices.mjs; do not edit.',
  'use crate::table::Detector;',
  '',
  'pub const DETECTORS: &[Detector] = &[',
  ...detectors.map((d) => `    Detector { name: ${JSON.stringify(d.name)}, vid: 0x${d.vid.toString(16).padStart(4, '0')}, pid: 0x${d.pid.toString(16).padStart(4, '0')}, interface: ${d.interface}, usage_page: 0x${d.usage.toString(16).padStart(4, '0')} },`),
  '];',
  '',
];
const out = path.join(process.cwd(), 'modules', 'msi-motherboard', 'src', 'devices_table.rs');
fs.mkdirSync(path.dirname(out), { recursive: true });
fs.writeFileSync(out, lines.join('\n'));
execFileSync(process.platform === 'win32' ? 'rustfmt.exe' : 'rustfmt', [out], { stdio: 'ignore' });
console.log(`generated ${detectors.length} MSI HID detectors from ${source}`);
