import fs from 'node:fs';
const commit = process.argv[3] ?? 'unknown';
const names = ["ASUS ROG Throne","ASUS ROG Throne Qi","ASUS ROG Throne Qi Gundam"];
const pids = ["0x18d9","0x18c5","0x1994"];
const rows = [];
for (let i=0;i<names.length;i++) rows.push(`    Detector { name: "${names[i]}", vid: 0x0b05, pid: ${pids[i]}, interface: 0, usage_page: 0x0000, usage: 0x0000 },`);
const out = [
    '// SPDX-License-Identifier: GPL-2.0-or-later',
    `// Generated by scripts/openrgb/port-asus-aura-headset-stand-devices.mjs from OpenRGB ${commit}; do not edit.`,
    'use crate::table::Detector;',
    '',
    'pub const DETECTORS: &[Detector] = &[',
    ...rows,
    '];',
];
fs.writeFileSync('modules/asus-aura-headset-stand/src/devices_table.rs', out.join('\n'));
console.log('generated 3 ASUS Aura headset stand detectors');
