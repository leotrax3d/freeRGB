#!/usr/bin/env python3
"""Report thin or incomplete module provenance records.

Scans modules/*/PROVENANCE.md and writes docs/legal/MODULE_PROVENANCE_GAPS.md
(line count and missing fields per module). It never edits PROVENANCE files.
A field counts as present when a keyword is found; that is a heuristic, not a
review. Whether the upstream attribution is correct is a manual task.

Usage: python scripts/check-module-provenance.py [--check]
"""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs/legal/MODULE_PROVENANCE_GAPS.md"
THIN_LINES = 15
FIELDS = {
    "upstream file": re.compile(r"upstream\s+file|\.(cpp|h|hpp|c|cs|py|js)\b", re.I),
    "authors": re.compile(r"authors?\b|copyright|\(c\)|contributors", re.I),
    "changes": re.compile(r"^#+\s*(changes|modifications)|\bchanges?:|behavio[u]?r transfer", re.I | re.M),
    "upstream project/commit": re.compile(r"(upstream|source).*(https?://|\b[0-9a-f]{40}\b)|\b[0-9a-f]{40}\b", re.I | re.S),
    "license": re.compile(r"licen[sc]e|SPDX|GPL", re.I),
}


def scan():
    rows = []
    for md in sorted((ROOT / "modules").glob("*/PROVENANCE.md")):
        text = md.read_text(encoding="utf-8", errors="replace")
        lines = len(text.splitlines())
        missing = [name for name, rx in FIELDS.items() if not rx.search(text)]
        rows.append((md.parent.name, lines, missing))
    return rows


def render(rows):
    thin = [r for r in rows if r[1] < THIN_LINES]
    out = [
        "# Module provenance gaps",
        "",
        "<!-- Generated by scripts/check-module-provenance.py. Do not edit by hand. -->",
        "",
        "Heuristic scan of `modules/*/PROVENANCE.md` (line count and required fields).",
        "It is not a review of upstream attribution and not a legal conclusion. The",
        "files were not edited; filling the gaps is manual work per module (FR-010, D3).",
        "",
        f"- Modules scanned: {len(rows)}",
        f"- Records shorter than {THIN_LINES} lines: {len(thin)}",
        f"- Records with at least one missing field: {sum(1 for r in rows if r[2])}",
        "",
        "Fields checked: upstream file(s) named, authors or copyright holders named, changes",
        "described, upstream project plus URL or commit, license stated.",
        "",
        "| Module | Lines | Missing fields |",
        "|---|---:|---|",
    ]
    for name, lines, missing in sorted(rows, key=lambda r: (r[1], r[0])):
        out.append(f"| {name} | {lines} | {', '.join(missing) or '-'} |")
    modules_without = sorted(p.name for p in (ROOT / "modules").iterdir()
                             if p.is_dir() and not (p / "PROVENANCE.md").exists())
    if modules_without:
        out += ["", "## Module directories without PROVENANCE.md", ""] + [f"- {m}" for m in modules_without]
    return "\n".join(out) + "\n"


def main():
    content = render(scan())
    if "--check" in sys.argv:
        current = OUT.read_text(encoding="utf-8") if OUT.exists() else ""
        if current != content:
            print("MODULE_PROVENANCE_GAPS.md is out of date", file=sys.stderr)
            return 1
        return 0
    with OUT.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(content)
    rows = scan()
    print(f"scanned {len(rows)} modules; thin: {sum(1 for r in rows if r[1] < THIN_LINES)}; wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
