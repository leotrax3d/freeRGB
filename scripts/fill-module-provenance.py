#!/usr/bin/env python3
"""Fill the generated attribution block of modules/*/PROVENANCE.md from an OpenRGB checkout.

Only the block between the BEGIN/END GENERATED markers is written; the rest of
each file is left alone. For every upstream file named in the existing
PROVENANCE.md (or, if none can be resolved, every .cpp/.h file of the upstream
controller directory) the block lists the upstream path, URL at the pinned
commit, SPDX line and copyright/author lines taken from the file header.
Unresolved names are listed so a human can check them. This is mechanical
extraction, not a legal review.

Usage: python scripts/fill-module-provenance.py --openrgb <checkout> [--module ID] [--check]
The commit comes from OPENRGB_COMMIT in .github/workflows/modules.yml and must
match the checkout HEAD.
"""
import argparse
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BEGIN = "<!-- BEGIN GENERATED PROVENANCE (scripts/fill-module-provenance.py) -->"
END = "<!-- END GENERATED PROVENANCE -->"
URL = "https://gitlab.com/CalcProgrammer1/OpenRGB"
SRC_EXT = (".cpp", ".h", ".hpp", ".c")
ATTR = re.compile(r"copyright|\(c\)|\bauthors?\b|SPDX-License-Identifier|\bby [A-Z][a-z]+|contributors|licen[sc]e", re.I)


def pinned_commit():
    text = (ROOT / ".github/workflows/modules.yml").read_text(encoding="utf-8")
    return re.search(r"OPENRGB_COMMIT:\s*([0-9a-f]{40})", text).group(1)


DATE = re.compile(r"[0-9]{1,2} +[A-Z][a-z]{2} +[0-9]{4}|(?:19|20)[0-9]{2}")


def header_lines(path):
    out = []
    try:
        lines = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return out
    for line in lines[:40]:
        s = line.strip()
        if not s.startswith(("/", "*", "#", "|", "\\")):
            if s:
                break
            continue
        s = s.lstrip("/*#|\\ \t-").rstrip("|/*\\ \t-").strip()
        s = re.sub(r"\s{2,}", " ", s)
        if not s:
            continue
        if ATTR.search(s) or DATE.search(s):
            if s not in out:
                out.append(s)
    return out


def family_dirs(mod_id, text, openrgb):
    names = set(re.findall(r"Controllers/([A-Za-z0-9_+.-]+)", text))
    port = ROOT / f"scripts/openrgb/port-{mod_id}-devices.mjs"
    if port.exists():
        ptxt = port.read_text(encoding="utf-8", errors="replace")
        names |= set(re.findall(r"Controllers/([A-Za-z0-9_+.-]+)", ptxt))
        names |= set(re.findall(r"'Controllers',\s*'([A-Za-z0-9_+.-]+)'", ptxt))
        names |= set(re.findall(r'"Controllers",\s*"([A-Za-z0-9_+.-]+)"', ptxt))
    return sorted(n for n in names if (openrgb / "Controllers" / n).is_dir())


def resolve(name, dirs, openrgb, index):
    cand = [openrgb / name, openrgb / "Controllers" / name]
    for c in cand:
        if c.is_file():
            return c
    base = Path(name).name
    for d in dirs:
        hits = sorted((openrgb / "Controllers" / d).rglob(base))
        if hits:
            return hits[0]
    hits = index.get(base, [])
    return hits[0] if len(hits) == 1 else None


def build(mod_dir, openrgb, commit, index):
    text = (mod_dir / "PROVENANCE.md").read_text(encoding="utf-8", errors="replace")
    text = text.split(BEGIN)[0]
    mod_id = mod_dir.name
    dirs = family_dirs(mod_id, text, openrgb)
    named = []
    for m in re.findall(r"`([^`\s]+\.(?:cpp|h|hpp|c)(?:/\.[a-z]+)?)(?:\s*::[^`]*)?`", text):
        names = [m]
        if "/." in m:
            stem, exts = m.split("/.", 1)[0], m.split("/.")[1:]
            base = stem.rsplit(".", 1)[0]
            names = [stem] + [base + "." + e for e in exts]
        for n in names:
            if n not in named:
                named.append(n)
    # also "A.cpp/.h" shorthand
    files, unresolved = [], []
    for n in named:
        p = resolve(n, dirs, openrgb, index)
        if p and p not in files:
            files.append(p)
        elif not p:
            unresolved.append(n)
    scope = "files named in the hand-written record"
    if not files and dirs:
        scope = "directory level (no named file resolved): all source files of the upstream controller directories"
        for d in dirs:
            for p in sorted((openrgb / "Controllers" / d).rglob("*")):
                if p.suffix in SRC_EXT:
                    files.append(p)
    gen = ""
    for name in ("port-%s-devices.mjs" % mod_id,):
        if (ROOT / "scripts/openrgb" / name).exists():
            gen = f"; device/detector tables generated by `scripts/openrgb/{name}`"
    rows = []
    for p in files:
        rel = p.relative_to(openrgb).as_posix()
        hdr = header_lines(p)
        spdx = next((h for h in hdr if "SPDX-License-Identifier" in h), "no SPDX line in header")
        attr = [h for h in hdr if "SPDX" not in h and "part of the OpenRGB" not in h] or ["no copyright/author line in header"]
        rows.append(f"| `{rel}` | [{commit[:12]}]({URL}/-/blob/{commit}/{rel}) | {spdx.replace('SPDX-License-Identifier:', '').strip()} | {'; '.join(attr)[:300]} |")
    lines = [BEGIN, "", "## Upstream attribution (generated)", "",
             f"Upstream: OpenRGB, {URL}, commit `{commit}`.",
             "Licence of the used files: GPL-2.0-or-later (SPDX column below is read from each header; where a header says otherwise the module licence needs a manual check).",
             f"Scope: {scope}.", "",
             "| Upstream file | URL at commit | SPDX | Copyright / author lines in header |", "|---|---|---|---|"]
    lines += rows or ["| (none resolved: no OpenRGB upstream file found; manual provenance check needed) | | | |"]
    lines += ["", f"Changes: ported to a Rust freeRGB module (process module under `modules/{mod_id}/`){gen}; behaviour changes are listed in the hand-written sections above.", ""]
    if unresolved:
        lines += ["Names in the hand-written record that could not be resolved in the checkout (manual check needed): " + ", ".join(f"`{u}`" for u in unresolved), ""]
    lines += ["Generated by mechanical header extraction; not a legal review.", END, ""]
    return text.rstrip("\n") + "\n\n" + "\n".join(lines)


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--openrgb", required=True)
    ap.add_argument("--module")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    openrgb = Path(a.openrgb)
    commit = pinned_commit()
    head = subprocess.run(["git", "-C", str(openrgb), "rev-parse", "HEAD"], capture_output=True, text=True).stdout.strip()
    if head != commit:
        sys.exit(f"checkout HEAD {head} != OPENRGB_COMMIT {commit}")
    index = {}
    for p in (openrgb / "Controllers").rglob("*"):
        if p.suffix in SRC_EXT:
            index.setdefault(p.name, []).append(p)
    changed = 0
    for md in sorted((ROOT / "modules").glob("*/PROVENANCE.md")):
        if a.module and md.parent.name != a.module:
            continue
        new = build(md.parent, openrgb, commit, index)
        old = md.read_text(encoding="utf-8", errors="replace")
        if new != old:
            changed += 1
            if not a.check:
                md.write_text(new, encoding="utf-8", newline="\n")
    print(f"{changed} PROVENANCE.md file(s) {'would change' if a.check else 'updated'}")
    return 1 if (a.check and changed) else 0


if __name__ == "__main__":
    sys.exit(main())
